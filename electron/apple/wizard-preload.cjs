const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('appleImport', {
  env: () => ipcRenderer.invoke('apple:env'),
  pickGpg: () => ipcRenderer.invoke('apple:pick-gpg'),
  pickFolder: t => ipcRenderer.invoke('apple:pick-folder', t),
  decryptOuter: (gpgFile, passcode) => ipcRenderer.invoke('apple:decrypt-outer', { gpgFile, passcode }),
  checkOutput: d => ipcRenderer.invoke('apple:check-output', d),
  setOutput: (dir, examiner) => ipcRenderer.invoke('apple:set-output', { dir, examiner }),
  startDownload: selected => ipcRenderer.invoke('apple:start-download', { selected }),
  pause: () => ipcRenderer.invoke('apple:pause'),
  resume: () => ipcRenderer.invoke('apple:resume'),
  retry: i => ipcRenderer.invoke('apple:retry', i),
  process: p => ipcRenderer.invoke('apple:process', p ? { passcode: p } : undefined), /*uwrp-b9*/
  openFolder: p => ipcRenderer.invoke('apple:open-folder', p),
  scanFolder: d => ipcRenderer.invoke('apple:scan-folder', d),
  folderImport: o => ipcRenderer.invoke('apple:folder-import', o),
  folderFinish: p => ipcRenderer.invoke('apple:folder-finish', p ? { passcode: p } : undefined),
  cancel: () => ipcRenderer.invoke('apple:cancel'),
  backups: root => ipcRenderer.invoke('apple:backups', root),
  backupList: root => ipcRenderer.invoke('apple:backup-list', root),
  backupSection: (dir, section, opts) => ipcRenderer.invoke('apple:backup-section', { dir, section, opts }),
  backupPreview: (dir, fileID) => ipcRenderer.invoke('apple:backup-preview', { dir, fileID }),
  backupHash: (dir, fileID) => ipcRenderer.invoke('apple:backup-hash', { dir, fileID }),
  backupTag: (items, tagged) => ipcRenderer.invoke('apple:backup-tag', { items, tagged }),
  tagState: () => ipcRenderer.invoke('apple:get-tag-state'),
  pickBackupZip: () => ipcRenderer.invoke('apple:pick-backup-zip'),
  backupExtract: (zip, dest) => ipcRenderer.invoke('apple:backup-extract', { zip, dest }),
  openBackups: root => ipcRenderer.send('uwrp-open-apple-backups', root),
  on: (ch, fn) => { const ok = ['apple:item', 'apple:dl-done', 'apple:status', 'apple:backup-root', 'apple:mode', 'apple:tag-state', 'apple:gpg-file', 'apple:folder-path']; if (ok.includes(ch)) ipcRenderer.on(ch, (_e, d) => fn(d)); },
});
